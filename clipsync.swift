// clipsync: share plain-text clipboard across Macs over Tailscale via a hub Mac.
// Watches NSPasteboard.changeCount, POSTs new text to the hub, and long-polls the
// hub for text copied on other Macs (outbound connections only). Password-manager
// copies (concealed/transient types) are never sent. Build: swiftc -O -target arm64-apple-macos14.0 clipsync.swift -o clipsync
import AppKit
import Foundation

let env = ProcessInfo.processInfo.environment
func config(_ name: String) -> String {
    let path = NSHomeDirectory() + "/.config/clipsync/" + name
    return ((try? String(contentsOfFile: path, encoding: .utf8)) ?? "")
        .trimmingCharacters(in: .whitespacesAndNewlines)
}
// Hub URL: CLIPSYNC_HUB env, else ~/.config/clipsync/hub (written by install.sh)
let hub = env["CLIPSYNC_HUB"] ?? config("hub")
let token = config("token")
if hub.isEmpty || token.isEmpty {
    FileHandle.standardError.write("clipsync: missing ~/.config/clipsync/hub or token\n".data(using: .utf8)!)
    exit(1)
}
// Unique per process: two Macs can share a computer name ("Mac mini").
let me = ProcessInfo.processInfo.hostName + "-" + UUID().uuidString.prefix(8)
let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
let maxBytes = 1_000_000

let pb = NSPasteboard.general
var lastCount = pb.changeCount
var lastText = pb.string(forType: .string)   // main thread only

func log(_ s: String) {
    FileHandle.standardError.write("\(Date()) \(s)\n".data(using: .utf8)!)
}

func call(_ path: String, json: [String: Any]? = nil, timeout: Double) -> (Int, [String: Any]?) {
    var r = URLRequest(url: URL(string: hub + path)!, timeoutInterval: timeout)
    r.setValue(token, forHTTPHeaderField: "X-Token")
    if let j = json {
        r.httpMethod = "POST"
        r.httpBody = try? JSONSerialization.data(withJSONObject: j)
    }
    let sem = DispatchSemaphore(value: 0)
    var code = 0
    var out: [String: Any]?
    URLSession.shared.dataTask(with: r) { d, resp, _ in
        code = (resp as? HTTPURLResponse)?.statusCode ?? 0
        if let d = d { out = try? JSONSerialization.jsonObject(with: d) as? [String: Any] }
        sem.signal()
    }.resume()
    sem.wait()
    return (code, out)
}

// Local copy -> hub
Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
    guard pb.changeCount != lastCount else { return }
    lastCount = pb.changeCount
    let types = Set((pb.types ?? []).map { $0.rawValue })
    if !types.isDisjoint(with: skipTypes) { return }
    let s = pb.string(forType: .string)
    if env["CLIPSYNC_DEBUG"] != nil {
        log("change \(lastCount): \(types.count) types, text \(s == nil ? "nil" : "\(s!.utf8.count)B")")
    }
    guard let t = s, t != lastText, t.utf8.count <= maxBytes else { return }
    lastText = t
    DispatchQueue.global().async {
        let (code, _) = call("/push", json: ["text": t, "from": me], timeout: 10)
        if code != 200 { log("push failed: HTTP \(code)") }
    }
}

// Hub -> local clipboard (long poll). Start from the hub's current id so a
// restart never overwrites what is already on this Mac's clipboard.
// One poll round; returns the updated `since` (-1 = ask the hub for its id).
func pollOnce(_ since: Int) -> Int {
    if since < 0 {
        let (code, j) = call("/id", timeout: 10)
        if code == 200, let id = j?["id"] as? Int { return id }
        sleep(5)
        return -1
    }
    let (code, j) = call("/wait?since=\(since)", timeout: 45)
    if code == 200, let id = j?["id"] as? Int, let t = j?["text"] as? String {
        if (j?["from"] as? String) != me, !t.isEmpty {
            DispatchQueue.main.async {
                guard t != lastText else { return }
                pb.clearContents()
                pb.setString(t, forType: .string)
                lastCount = pb.changeCount
                lastText = t
            }
        }
        return id
    }
    if code != 204 {
        log("wait failed: HTTP \(code)")
        sleep(5)
    }
    return since
}

Thread.detachNewThread {
    var since = -1
    // A detached thread has no run loop to drain autoreleased Foundation objects,
    // so each poll needs its own pool (without it memory grew ~1 GB a month).
    while true { autoreleasepool { since = pollOnce(since) } }
}

log("clipsync started as \(me), hub \(hub)")
RunLoop.main.run()
